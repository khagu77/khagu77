// 스크립트 기본 교정 (PC 안에서 규칙으로만 고침 - 외부로 보내지 않음)
// - 공백: 겹친 공백, 문장부호 앞뒤 띄어쓰기
// - 자주 틀리는 맞춤법: 됬→됐, 몇일→며칠, 되요→돼요, 할께→할게 …
// - 의존명사 띄어쓰기 일부: 할수있다→할 수 있다, 그런것같다→그런 것 같다, 할때→할 때, 할거예요→할 거예요, 그것때문에→그것 때문에
// 문맥을 보는 교정이 아니므로 확실히 틀린 경우만 고친다. 결과: { text, fixes(고친 곳 수) }

(function (global) {
  const HANGUL_BASE = 0xac00;
  const JONG_N = 4; // ㄴ 받침
  const JONG_L = 8; // ㄹ 받침

  function jong(ch) {
    const c = ch ? ch.charCodeAt(0) - HANGUL_BASE : -1;
    return c >= 0 && c < 11172 ? c % 28 : -1;
  }

  // [틀린 표기, 바른 표기] - 글자 그대로 바꿔도 다른 낱말을 망가뜨리지 않는 것만
  const WORDS = [
    ["됬", "됐"],
    ["몇일", "며칠"],
    ["몇 일", "며칠"],
    ["어떻해", "어떡해"],
    ["어떻하", "어떡하"],
    ["금새", "금세"],
    ["왠만", "웬만"],
    ["웬지", "왠지"],
    ["일일히", "일일이"],
    ["깨끗히", "깨끗이"],
    ["틈틈히", "틈틈이"],
    ["곰곰히", "곰곰이"],
    ["번번히", "번번이"],
    ["일찌기", "일찍이"],
    ["설겆이", "설거지"],
    ["오랫만", "오랜만"],
    ["희안하", "희한하"],
    ["희안한", "희한한"],
    ["어의없", "어이없"],
    ["역활", "역할"],
    ["뵈요", "봬요"],
    ["되요", "돼요"],
    ["않되", "안 되"],
    ["않돼", "안 돼"],
    ["문안하", "무난하"],
    ["문안한", "무난한"],
    ["구지 ", "굳이 "],
    ["궂이", "굳이"],
    ["어떻케", "어떻게"],
    ["그럴려고", "그러려고"],
    ["할려고", "하려고"],
    ["갈려고", "가려고"],
    ["볼려고", "보려고"],
    ["올려고", "오려고"],
    ["줄려고", "주려고"],
  ];

  // '것' 앞에 붙어 한 낱말이 되는 글자 (별것, 날것, 탈것, 들것) - 띄우지 않음
  const GEOT_WORD = new Set(["별", "날", "탈", "들"]);

  function correctText(input) {
    let s = String(input || "");
    let fixes = 0;
    const sub = (re, fn) => {
      s = s.replace(re, (...m) => {
        // 문자열 바꿈의 $1, $2 는 찾은 묶음으로 펼친다
        const out = typeof fn === "function" ? fn(...m) : fn.replace(/\$(\d)/g, (_, k) => m[Number(k)] || "");
        if (out !== m[0]) fixes++;
        return out;
      });
    };

    // 1) 공백 정리 (고친 곳 수에는 넣지 않음)
    s = s.replace(/[\t 　]+/g, " ").replace(/ {2,}/g, " ").trim();

    // 2) 맞춤법
    for (const [wrong, right] of WORDS) {
      if (s.includes(wrong)) sub(new RegExp(wrong, "g"), right);
    }
    // ㄹ받침+께 → 게 (할께요 → 할게요). 뒤에 한글이 바로 이어지면(…께서) 그대로 둔다.
    sub(/([가-힣])께(?=요|[^가-힣]|$)/g, (m, a) => (jong(a) === JONG_L ? `${a}게` : m));

    // 3) 의존명사 띄어쓰기
    // 할수있다 / 할수 없다 → 할 수 있다
    sub(/([가-힣])수 ?(있|없)/g, (m, a, b) => (jong(a) === JONG_L ? `${a} 수 ${b}` : m));
    // 수있다(앞은 이미 띄움) → 수 있다 ('수없이'는 한 낱말이라 그대로)
    sub(/(^| )수(있|없(?!이))/g, "$1수 $2");
    // 것같다 → 것 같다
    sub(/것같/g, "것 같");
    // 그런것 / 하는것 / 할것 → 그런 것 (관형형 ㄴ·ㄹ 받침 뒤)
    sub(/([가-힣])것(?= |같|이|은|을|도|만|$)/g, (m, a) =>
      (jong(a) === JONG_N || jong(a) === JONG_L) && !GEOT_WORD.has(a) ? `${a} 것` : m,
    );
    // 할때 → 할 때 (때문 은 아래에서)
    sub(/([가-힣])때(?!문)/g, (m, a) => (jong(a) === JONG_L ? `${a} 때` : m));
    // 할거예요 / 갈거야 → 할 거예요
    sub(/([가-힣])거(?=예요|에요|야|다|든|라|니|지|고|요)/g, (m, a) => (jong(a) === JONG_L ? `${a} 거` : m));
    // 그것때문에 → 그것 때문에
    sub(/([가-힣])때문/g, "$1 때문");

    // 4) 문장부호 띄어쓰기: 앞 공백 없애고, 뒤에 글자가 바로 오면 한 칸 (1.5, ..., ?! 는 그대로)
    sub(/ +([,!?)\]]|\.(?!\.))/g, "$1");
    sub(/([([]) +/g, "$1");
    sub(/([,!?])(?=[가-힣A-Za-z])/g, "$1 ");
    sub(/([가-힣])\.(?=[가-힣])/g, "$1. ");

    s = s.replace(/ {2,}/g, " ").trim();
    return { text: s, fixes };
  }

  global.ScriptCorrect = { correctText };
  if (typeof module !== "undefined") module.exports = global.ScriptCorrect;
})(typeof window !== "undefined" ? window : globalThis);
